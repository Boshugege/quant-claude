"""由 1628 生成 1629：委托结构的 EWMA 由 α=0.3 改为 0.5（压换手；c2 中 α=0.5 比 0.3 换手低约 0.006–0.010），其余不变。
用法：python3 因子实验/build_1629.py"""
SRC = "因子代码/1628_1610加委托结构.py"
DST = "因子代码/1629_1610加委托结构平滑0.5.py"
s = open(SRC, encoding="utf-8").read()


def rep(a, b, n=1):
    global s
    assert s.count(a) == n, (s.count(a), a[:80])
    s = s.replace(a, b)


rep('''    """【1628：1610 加委托结构】= 1610（公榜 0.891）原样，加第 13 根 B13 委托结构（盘口排队的人数与挂单规模）：
      B13 × 0.2234（先做 EWMA α=0.3）''', '''    """【1629：1610 加委托结构（平滑 0.5）】= 1628 把委托结构的 EWMA 由 α=0.3 改为 0.5（压换手），其余与 1628 相同。
    以下为 1628 的说明（权重不变，平滑改为 0.5）。
    【1628：1610 加委托结构】= 1610（公榜 0.891）原样，加第 13 根 B13 委托结构（盘口排队的人数与挂单规模）：
      B13 × 0.2234（先做 EWMA α=0.3）''')
rep('''      B13 × 0.2234（先做 EWMA α=0.3）：委托结构（1628 新增，见上）''', '''      B13 × 0.2234（先做 EWMA α=0.5）：委托结构（1628 新增，1629 平滑改为 0.5，见上）''')
rep('''        (main_b13, 0.2234, 0.3, {}),''', '''        (main_b13, 0.2234, 0.5, {}),''')
open(DST, "w", encoding="utf-8").write(s)
print("写出", DST)
