def load():
    rows = []
    for d in sorted(glob.glob(str(ROOT / "工具" / "评分机" / "结果" / "*"))):
        f = os.path.join(d, "result.json")
        if not os.path.exists(f):
            continue
        j = json.load(open(f))
        nm = (j.get("meta") or {}).get("name")
        if nm in WANT and (j.get("metrics") or {}):
            rows.append((WANT[nm], os.path.basename(d), j))
    rows.sort(key=lambda r: (r[0][0].isdigit() is False, r[0][0]))
    return rows


